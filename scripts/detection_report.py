"""Phase 3: run the detection experiment and write the results JSON and markdown report.

Usage (from pipeline/):
    uv run python -I ../scripts/detection_report.py ../data/processed/v0.2.0 \
        --json ../docs/detection/results.json --out ../docs/detection-report.md

Interpretation lives in docs/decisions/0021-detection-methodology.md; this file only reports numbers.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from faultiq.detection.experiment import run

NAMES = {
    "limit_rules": "Limit rules",
    "economizer_rules": "Economizer rules",
    "normal_model": "Normal model",
}


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x:.0%}"


def label(key: str) -> str:
    family, points = key.split("/")
    return f"{NAMES[family]} ({points} points)"


def headline(res: dict[str, Any]) -> list[str]:
    lines = [
        "| Dataset | Detector | ROC-AUC | Recall | False alarms | Precision | Abstained (faulty / normal) |",
        "|---|---|---|---|---|---|---|",
    ]
    for ds in ("simulated", "experimental"):
        for key, v in res[ds]["detectors"].items():
            t, a = v["test"], v["abstained_share"]
            lines.append(
                f"| {ds} | {label(key)} | {t['auc']} | {pct(t['recall'])} | {pct(t['false_positive_rate'])} "
                f"| {pct(t['precision'])} | {pct(a['faulty'])} / {pct(a['normal'])} |"
            )
    return lines


def dataset_section(name: str, data: dict[str, Any]) -> list[str]:
    dets = data["detectors"]
    keys = list(dets)
    lines = [f"## {name.capitalize()} set", "", "### Coverage", ""]
    lines += ["| Fault | Test windows | Observable share |", "|---|---|---|"]
    for c in data["coverage"]:
        lines.append(
            f"| {c['fault']} | {c['windows']} | {pct(c['observable_share'])} |"
        )
    lines += ["", "### Confusion matrices (test windows)", ""]
    lines += [
        "| Detector | TP | FP | FN | TN | Threshold |",
        "|---|---|---|---|---|---|",
    ]
    for k, v in dets.items():
        t = v["test"]
        thr = v.get("threshold", v.get("thresholds_by_test_season"))
        lines.append(
            f"| {label(k)} | {t['tp']} | {t['fp']} | {t['fn']} | {t['tn']} | {thr} |"
        )

    lines += ["", "### Recall by fault and severity (test windows)", ""]
    lines += ["| Fault | Windows | " + " | ".join(label(k) for k in keys) + " |"]
    lines += ["|---|---|" + "---|" * len(keys)]
    rows: dict[tuple[str, Any], dict[str, Any]] = {}
    for k in keys:
        for r in dets[k]["recall_by_fault"]:
            entry = rows.setdefault(
                (r["fault"], r["intensity"]), {"windows": r["windows"]}
            )
            entry[k] = r["recall"]
    for (fault, inten), entry in sorted(
        rows.items(), key=lambda kv: (kv[0][0], kv[0][1] or 0)
    ):
        name_ = f"{fault} {'' if inten is None else format(inten, 'g')}".strip()
        lines.append(
            f"| {name_} | {entry['windows']} | "
            + " | ".join(pct(entry.get(k)) for k in keys)
            + " |"
        )

    lines += ["", "### False alarms on normal windows, by operating mode", ""]
    lines += [
        "| Detector | "
        + " | ".join(
            m["mode"] or "unknown" for m in dets[keys[0]]["false_alarms_by_mode"]
        )
        + " |"
    ]
    lines += ["|---|" + "---|" * len(dets[keys[0]]["false_alarms_by_mode"])]
    for k in keys:
        cells = [
            f"{pct(m['false_alarm_rate'])} of {m['windows']}"
            for m in dets[k]["false_alarms_by_mode"]
        ]
        lines.append(f"| {label(k)} | " + " | ".join(cells) + " |")
    return lines


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("processed", type=Path)
    parser.add_argument("--json", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)

    res = run(args.processed)
    args.json.parent.mkdir(parents=True, exist_ok=True)
    args.json.write_text(json.dumps(res, indent=2, sort_keys=True, default=str) + "\n")

    lines = [
        "# Detection report: Phase 3 baselines",
        "",
        (
            f"> Generated by `scripts/detection_report.py` on {res['generated']} (detection {res['detection_version']}, "
            f"pipeline {res['pipeline_version']}). Numbers only; interpretation and limitations are in"
        ),
        "> [ADR 0021](decisions/0021-detection-methodology.md). Full results: [detection/results.json](detection/results.json).",
        "",
        "**Method in one paragraph.** Each file-hour is one window. A faulty window is scored only when its fault "
        f"could physically show for at least {res['min_minutes']} minutes; a normal window when at least "
        f"{res['min_minutes']} minutes were steady. Simulated split: "
        + ", ".join(f"{k} {v}" for k, v in res["splits"]["simulated"].items())
        + ". "
        f"Experimental split: {res['splits']['experimental']}. Each alarm threshold is the lowest value that keeps "
        f"false alarms at or below {pct(res['max_false_alarm_rate_on_validation'])} of normal validation windows, "
        "then it is frozen before test windows are scored. Detectors abstain where outdoor air is outside the "
        "range seen in fault-free training; abstained windows count as no alarm.",
        "",
        (
            "**Reading the numbers.** Recall and ROC-AUC don't depend on how common faults are. Precision does: the "
            "simulated test set is about 96% faulty windows, so its precision looks high for any detector."
        ),
        "",
        "## Headline results (held-out test windows)",
        "",
        *headline(res),
        "",
        *dataset_section("simulated", res["simulated"]),
        "",
        *dataset_section("experimental", res["experimental"]),
        "",
    ]
    args.out.write_text("\n".join(lines))
    print(f"Wrote {args.out} and {args.json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
